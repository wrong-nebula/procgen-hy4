#!/usr/bin/env python3
"""Writes docs/KIT_REFERENCES.md: the atlas recipes, atlas sources and plate images each kit
module is derived from, read from the `references` block of the generated module documents."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
rows = []
for family in ("greenhouse", "site", "isle"):
    for doc in sorted((ROOT / family).glob("*/*.json")):
        if doc.name == "modules.json":
            continue
        r = json.loads(doc.read_text()).get("references") or {}
        cell = lambda key: ", ".join(r.get(key, [])) or "-"
        rows.append(f"| `{doc.stem}` | {family}/{doc.parent.name} | {cell('atlas')} | {cell('sources')} | {cell('plates')} | {r.get('notes', '-')}{' Also: ' + '; '.join(r['other']) + '.' if r.get('other') else ''} |")
text = """# Kit references

Generated by `recipes/list_references.py`; do not edit. Each kit module records what it was
derived from:

- **Atlas recipes**: design recipes in the detail atlas (`References/data.json` in the main
  checkout), each with its own observation, parameters and assembly contract.
- **Atlas sources**: the source records behind them (Eiffel plates, Vitry, Laeken and Kew
  photographs, reference prints).
- **reference**: images in the reference library (`experiments/references/plates`, ids `sNN`).

Layout dimensions come from the layout tool; member sizes are design assumptions unless the
notes cite a recipe that states them. `byteask verify` checks that every id resolves.

| Module | Kit | Atlas recipes | Atlas sources | reference | What was taken |
|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
(ROOT.parent / "docs" / "KIT_REFERENCES.md").write_text(text)
print(f"{len(rows)} modules")
